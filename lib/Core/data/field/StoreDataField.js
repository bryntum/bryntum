import DataField from './DataField.js';
import ObjectHelper from '../../helper/ObjectHelper.js';
import StringHelper from '../../helper/StringHelper.js';

/**
 * @module Core/data/field/StoreDataField
 */

const
    isIdAutoGenerated = id => typeof id === 'string' && id.startsWith('_generated'),
    // Placed in record.meta.modified for fields in granular mode, instead of a snapshot of the
    // original value. Marks the field as modified while delegating the actual dirty state (and
    // revert) to the backing store, which tracks its own changes exactly
    granularModifiedMarker = Symbol('granularStoreFieldModified');

/**
 * This field class handles fields that accepts an array that is then converted to a store.
 *
 * ```javascript
 * class Task extends Model {
 *     static fields = [
 *         'name',
 *         // Store field
 *         { name : 'subTasks', type : 'store', storeClass : Store }
 *     ];
 * }
 * ```
 *
 * A record can be constructed like this:
 *
 * ```javascript
 * const task = new Task({
 *     name : 'Task 1',
 *     subTasks : [
 *         { text : 'Something', done : false },
 *         { text : 'Some other thing', done : true }
 *     ]
 * };
 * ```
 *
 * Or by populating a store:
 *
 * ```javascript
 * const store = new Store({
 *     modelClass : Task,
 *     data : [
 *         {
 *             name : 'Task 1',
 *             subTasks : [
 *                 { text : 'Something', done : false },
 *                 { text : 'Some other thing', done : true }
 *             ]
 *         },
 *         ...
 *     ]
 * });
 * ```
 *
 * Whenever the store or its records are manipulated, the field will be marked as modified:
 *
 * ```javascript
 * // These will all be detected as modifications
 * task.subTasks.first.done = true;
 * task.subTasks.last.remove();
 * task.subTasks.add({ text : 'New task', done : false });
 * ```
 *
 * <div class="warning">
 * Note that the underlying store by default will be configured with <code>syncDataOnLoad</code> set
 * to <code>true</code>
 * </div>
 *
 * By default, a change inside the field is tracked as a snapshot of the whole field value - the pre-change
 * array is kept as the field's original value (for {@link Core.data.Model#function-getUnmodified},
 * {@link Core.data.Model#function-revertChanges} and the {@link Core.data.stm.StateTrackingManager}), and
 * the owning record's `update` event carries `{ value, oldValue }` as full arrays. The serialized value is
 * produced lazily and cached, so loading a dataset does not eagerly serialize the field.
 *
 * ## Granular updates
 *
 * When the backing store is tracked by a {@link Core.data.stm.StateTrackingManager} with
 * {@link Core.data.stm.StateTrackingManager#config-trackStoreDataFields} enabled, mutations of the store are
 * handled granularly - no full array snapshots of the field value are produced. The STM records per-record
 * row actions instead of field snapshots, and the owning record's `update` event reports the field as a
 * granular delta (`{ isGranular : true, value, recordChanges }`) rather than `{ value, oldValue }`. This
 * makes undo/redo of large nested stores (for example calendar intervals) much cheaper in time and memory.
 * See {@link Core.data.stm.StateTrackingManager#config-trackStoreDataFields} for the full behavioral
 * contract, and the [Store type fields](#Core/guides/data/storefields.md) guide for an overview.
 *
 * ## See also
 *
 * - {@link Core.data.field.DataField} - Base field class with common configs
 * - {@link Core.data.Store} - The store class used to hold data
 * - [Store type fields](#Core/guides/data/storefields.md) - guide
 *
 * @extends Core/data/field/DataField
 * @classtype store
 * @datafield
 */
export default class StoreDataField extends DataField {
    static $name = 'StoreDataField';

    static type = 'store';

    // Exposed for tests and for code that needs to recognize the marker in record.meta.modified
    static granularModifiedMarker = granularModifiedMarker;

    /**
     * Store class to use when creating the store.
     *
     * ```javascript
     * class TodoStore extends Store {
     *     ...
     * }
     *
     * class Task extends Model {
     *     static fields = [
     *         { type : 'store', name : 'todoItems', storeClass : TodoStore }
     *     ];
     * }
     * ```
     *
     * @config {Class} storeClass
     * @ts-returns {typeof Store}
     */

    /**
     * Model class to use for the store (can also be configured as usual on the store class, this config is for
     * convenience).
     *
     * ```javascript
     * class TodoItem extends Model {
     *   ...
     * }
     *
     * class Task extends Model {
     *     static fields = [
     *         { type : 'store', name : 'todoItems', storeClass : Store, modelClass : TodoItem }
     *     ];
     * }
     * ```
     *
     * @config {Class} modelClass
     * @ts-returns {typeof Model}
     */

    /**
     * Optional store configuration object to apply when creating the store.
     *
     * ```javascript
     * class Task extends Model {
     *     static fields = [
     *         {
     *             type       : 'store',
     *             name       : 'todoItems',
     *             storeClass : Store,
     *             store      : {
     *                 syncDataOnLoad : false
     *             }
     *         }
     *     ];
     * }
     * ```
     *
     * @config {StoreConfig} store
     */

    /**
     * When `true`, the backing store is created on first access of `record.<fieldName>` instead of eagerly for
     * every record, saving memory for records that never use the field.
     *
     * Not supported for store fields that take part in scheduling calculations, such as a calendar's `intervals`.
     * Those stores are always created up front.
     *
     * ```javascript
     * class Resource extends Model {
     *     static fields = [
     *         { name : 'rateTables', type : 'store', storeClass : RateTableStore, lazy : true }
     *     ];
     * }
     * ```
     *
     * @config {Boolean} lazy
     * @default false
     */

    /**
     * For a {@link #config-lazy} field, whether loading a record with data for this field also creates its store,
     * rather than waiting for first access. Records loaded without data for the field still get no store.
     *
     * Enable it for a field whose sub-records must be reachable as soon as the record is loaded, even if nothing
     * reads the field itself.
     *
     * @config {Boolean} createStoreOnLoad
     * @default false
     */

    // Initializer, called when creating a record. Sets up the store and populates it with any initial data.
    // For `lazy` fields this runs on first genuine access (see `getOrCreateStore`) instead of at construction.
    init(data, record, chronoCallback) {
        const
            me        = this,
            storeName = `${me.name}Store`,
            config    = {
                // Optimization when used from sources, don't create a stack in Base
                skipStack      : true,
                syncDataOnLoad : true,
                // Incoming data is not expected to be polluted
                useRawData     : false
            };

        if (me.store) {
            ObjectHelper.assign(config, me.store);
        }

        // Optionally apply modelClass, for convenient configuration
        if (me.modelClass) {
            config.modelClass = me.modelClass;
        }

        // Call optional initializer (initSubTasksStore for subTasks field) on the record, letting it manipulate the
        // config before creating a store
        record[`init${StringHelper.capitalize(storeName)}`]?.(config);

        if (!config.storeClass && !me.storeClass) {
            throw new Error(`Field '${me.name}' with type 'store' must have a storeClass configured`);
        }

        // Store has to be assigned on the record, field is shared
        const store = record.meta[storeName] = new (config.storeClass || me.storeClass)(config);

        if (me.complexMapping) {
            ObjectHelper.setPath(data, me.dataSource, store);
        }
        else {
            data[me.dataSource] = store;
        }

        // Don't warn about generated ids, responsibility lies elsewhere
        store.verifyNoGeneratedIds = false;
        // Marks the store as backing a store type field - the STM keeps such stores in a separate registry
        store.$isStoreFieldStore = true;
        // Keep track of if id should be included when serializing or not
        store.usesId = me.usesId || !store.count || !store.every(record => record.hasGeneratedId);
        // The current value (the persistable array representation of the store's records) is cached behind
        // the Store#currentValue accessor. The getter fills the cache on first read and refreshes it when
        // the storage generation has changed since (records added/removed, dataset replaced). Record field
        // updates do not bump the generation - those refresh or invalidate the cache through the change
        // listener below
        store.$storeDataField = me;
        store.$storeDataFieldRecord = record;
        store.$currentValue = null;
        store.$currentValueGeneration = -1;

        me.setupStoreListeners(store, record);

        me.$chrono && chronoCallback(me, store);

        // Opt-in granular STM tracking of the backing store. Normally handled when the record joins an STM
        // tracked store (ModelStm#joinStore), this covers lazy fields whose store is created after joining
        if (record.stm?.trackStoreDataFields && !store.stm) {
            record.stm.addStore(store);
        }

        return store;
    }

    // Wires the backing store's events to the owning record. Two modes, switched at runtime by the
    // STM tracking the store (StateTrackingManager#trackStoreDataFields):
    //
    // - Snapshot mode (default): the pre-change value is cached and serves as the field's old value,
    //   mutations are propagated to the owning record through record.set()
    // - Granular mode: no full-array snapshots on mutation. Per-record deltas are collected from the
    //   store's own events - the only point where value/oldValue per record is available without
    //   serializing anything - and reported through the owning record's update event
    setupStoreListeners(store, record) {
        const
            me         = this,
            isGranular = () => Boolean(store.stm?.trackStoreDataFields);

        // Snapshot mode only: refreshes stale caches so that they hold the value as it is BEFORE a
        // mutation is applied - during the change propagation below, those cached values serve as the
        // fields' "old value" (comparisons, the update event payload, STM undo). Effectively this defers
        // producing the value from dataset load time (where it is expensive and usually never read) to
        // the first change. Not while the store's own data is being set, and not while this field is
        // mid-propagation - serializing at those points would capture a post-change value as the "old" one
        const captureOldValue = () => {
            if (!isGranular() && !store.$isSettingStoreFieldData && !me.$isUpdatingRecord) {
                me.captureAncestorValues(store, record);
            }
        };

        store.ion({
            // Before a mutation: make sure the cache holds the pre-change value (see captureOldValue)
            beforeAdd    : captureOldValue,
            beforeRemove : captureOldValue,
            beforeUpdate : captureOldValue,

            // After a mutation: propagate the change to the owning record (marks the record modified,
            // fires its update event) and keep the cached current value in sync
            change : ({ action }) => {
                if (isGranular()) {
                    me.onGranularChange(store, record);
                }
                else if (!store.$isSettingStoreFieldData) {
                    const
                        value                     = me.getValue(store, record),
                        oldPreserveCurrentDataset = store.$preserveCurrentDataset;

                    store.$preserveCurrentDataset = me.subStore && (
                        action === 'update' || action === 'remove' || action === 'add'
                    );

                    me.$isUpdatingRecord = true;
                    record.set(me.name, value);
                    me.$isUpdatingRecord = false;

                    store.$preserveCurrentDataset = oldPreserveCurrentDataset;

                    // cache the field current value
                    store.currentValue = value;
                }
                else {
                    // Applying a new dataset - invalidate. The generation covers membership changes on its
                    // own, but a sync-diff may consist of record updates only, which do not bump it
                    store.$currentValue = null;
                    store.$currentValueGeneration = -1;
                }
            }
        });
    }

    // Refreshes the stale cache of this field's store AND of every store field store up the owning
    // record's ancestor chain, so they all hold the value as it is BEFORE a mutation is applied.
    // Must happen before the mutation: an ancestor's serialization reads through this store's cache
    // accessor, which recomputes once the mutation has bumped the storage generation - priming an
    // ancestor after the mutation would capture post-change content as its "old value", making the
    // ancestor's own change propagation see the update as a no-op and silently drop it (membership
    // changes only - record updates do not bump the generation)
    captureAncestorValues(store, record) {
        void store.currentValue;

        record.stores?.forEach(parentStore => {
            if (parentStore.$storeDataField && !parentStore.stm?.trackStoreDataFields &&
                !parentStore.$isSettingStoreFieldData) {
                parentStore.$storeDataField.captureAncestorValues(parentStore, parentStore.$storeDataFieldRecord);
            }
        });
    }

    // Granular mode: buffers per-record deltas between the store's specific events (update/add/remove)
    // and its change event, where onGranularChange flushes them into the owning record's update event.
    // Wired by the STM when the store is registered with it, so untracked (snapshot mode) stores carry
    // no granular footprint
    setupGranularBuffer(store) {
        if (store.$granularChanges) {
            return;
        }

        const isGranular = () => Boolean(store.stm?.trackStoreDataFields);

        store.$granularChanges = [];

        store.ion({
            update : ({ record : subRecord, changes }) => {
                if (isGranular() && !store.$isSettingStoreFieldData) {
                    // Keep the native changes object ({ field : { value, oldValue } }) by reference -
                    // copying would read lazy values of nested granular fields, forcing serialization
                    store.$granularChanges.push({ id : subRecord.id, action : 'update', changes });
                }
            },

            add : ({ records }) => {
                if (isGranular() && !store.$isSettingStoreFieldData) {
                    for (const subRecord of records) {
                        store.$granularChanges.push({ id : subRecord.id, action : 'add', data : subRecord.persistableData });
                    }
                }
            },

            remove : ({ records }) => {
                if (isGranular() && !store.$isSettingStoreFieldData) {
                    for (const subRecord of records) {
                        store.$granularChanges.push({ id : subRecord.id, action : 'remove', data : subRecord.persistableData });
                    }
                }
            }
        });
    }

    // Granular mode handler for the backing store's change event. No full-array snapshots: the field's
    // modified state mirrors the store's own dirty state and the owning record's update event carries
    // the per-record deltas buffered by the update/add/remove listeners
    onGranularChange(store, record) {
        const
            me         = this,
            { name }   = me,
            wasMarked  = record.meta.modified[name] === granularModifiedMarker;

        // The value changed - recompute on demand at next read (unconditional - even a plain reorder
        // changes the serialized representation)
        store.$currentValue = null;
        store.$currentValueGeneration = -1;

        // The field's modified state mirrors the backing store's own dirty state
        me.updateGranularModified(store, record);

        if (store.$isSettingStoreFieldData) {
            // Applying a new dataset - handled by the regular set() path, deltas are meaningless
            if (store.$granularChanges) {
                store.$granularChanges.length = 0;
            }

            return;
        }

        const recordChanges = store.$granularChanges ?? [];

        // Nothing to report: no per-record deltas (e.g. a sort/filter/group change) and no dirty state
        // transition. The dirty<->clean transitions must go through even with an empty delta - commit
        // and revert rely on the propagation to refresh the owning store's modified bag
        if (!recordChanges.length && wasMarked === (record.meta.modified[name] === granularModifiedMarker)) {
            return;
        }

        // Keep track of if id should be included when serializing or not (snapshot mode maintains
        // this in set() during propagation, which granular mode bypasses)
        store.usesId = me.usesId || !store.count || !store.every(subRecord => subRecord.hasGeneratedId);

        const val = {
            isGranular : true,
            recordChanges,

            // The complete current value, serialized on demand (and cached) at first read. Reading it
            // after further mutations yields the then-current state, not the state at event time
            get value() {
                return store.currentValue;
            }
        };

        if (store.$granularChanges) {
            store.$granularChanges = [];
        }

        record.generation++;

        // Notify joined stores (fires the update/change events, maintains modified bags).
        // Deliberately not record.set() - there is no snapshot to compare or store, and
        // the STM tracks the backing store itself rather than field-level snapshots.
        // Silent when this change is a silent revertChanges() delegation
        record.afterChange({ [name] : val }, { [name] : val }, Boolean(store.$isRevertingSilently));
    }

    // Granular mode does not snapshot the original value. The field's modified state in
    // record.meta.modified mirrors the backing store's own dirty state, using a shared marker
    updateGranularModified(store, record) {
        const
            { meta }   = record,
            { name }   = this;

        // Mirrors the modification tracking suppression in Model#inSet (engine speeds initial
        // commit up by not recording changes): suspended tracking clears the dirty state,
        // ignoreBag leaves it untouched
        if (record.stores?.some(parentStore => parentStore.modificationsTracking > 0)) {
            delete meta.modified[name];

            return;
        }

        if (record.ignoreBag) {
            return;
        }

        // hasChanges, not changes - the latter allocates the added/removed/modified arrays just to
        // test truthiness, in a path that runs on every sub-record mutation
        if (store.hasChanges) {
            meta.modified[name] = granularModifiedMarker;

            // Changes applied while the record is being materialized (during a sync request) are
            // tracked separately, they need a second sync request of their own
            if (record.isBeingMaterialized) {
                meta.modifiedMaterialized = meta.modifiedMaterialized ?? {};
                meta.modifiedMaterialized[name] = granularModifiedMarker;
            }
        }
        else {
            // The store is back at its original state - the field is no longer modified
            delete meta.modified[name];
        }
    }

    // The current value - the persistable array representation of the store's records. While this field is
    // propagating a change from its own store to the record, the cache deliberately still holds the
    // pre-change value, which is what comparisons and old-value capture need at that point
    currentValueOf(store) {
        return this.$isUpdatingRecord ? store.$currentValue : store.currentValue;
    }

    defineAccessor(target, force) {
        // A chrono field's identifier must exist before the record enters the graph, too early for a lazy store
        if (this.lazy && this.$chrono) {
            throw new Error(`Field '${this.name}': 'lazy' is not supported for chrono store fields`);
        }

        super.defineAccessor(target, force);
    }

    // A `lazy` field's store is created when `record.<fieldName>` is first read. Not reached for a record class
    // declaring its own `get <fieldName>()`, which then owns creating the store (Gantt's TaskModel for `baselines`)
    buildGetter(name, dataSource) {
        const
            me                 = this,
            { complexMapping } = me;

        if (!me.lazy) {
            return super.buildGetter(name, dataSource);
        }

        // This field owns creating its store, `set` checks this before creating one behind a record's own accessor
        me.$createsStoreOnAccess = true;

        // no arrow functions here, need `this` to change to instance (the record).
        // Until the store exists, `data` holds the raw value it is built from. Always yield a store
        return complexMapping
            ? function() {
                const value = this.complexGet(name, dataSource);

                return value?.isStore ? value : this.$meta.fields.map[name].getOrCreateStore(this);
            }
            : function() {
                // Inlined copy of Model#flatGet, to save a fn call since this is hit very often
                if (this.batching && name in this.meta.batchChanges) {
                    return this.meta.batchChanges[name];
                }

                const value = this.data[dataSource];

                return value?.isStore ? value : this.$meta.fields.map[name].getOrCreateStore(this);
            };
    }

    /**
     * Returns the sub-store, creating it on demand for `lazy` fields. App code uses `record.<fieldName>` instead,
     * this is for callers holding a field definition rather than a name-bound accessor.
     * @internal
     * @param {Core.data.Model} record The record owning the store field
     * @returns {Core.data.Store} The sub-store, created if it didn't exist
     */
    getOrCreateStore(record) {
        const me = this;

        let store = record.meta[`${me.name}Store`];

        if (!store) {
            // No chronoCallback needed, lazy store fields are never chrono fields
            store = me.init(record.data, record, () => {});

            // Let the record wire the new store into the engine graph
            record.onLazyStoreCreated?.(me.name, store);

            // Apply any loaded value parked by Model#initInitables, now that there is a store to apply it to
            record.meta.initableValues?.size && record.assignInitables();
        }

        return store;
    }

    // Called when setting a new value to the field on a record
    set(value, data, record) {
        const
            me        = this,
            storeName = `${me.name}Store`;

        let { [storeName] : store } = record.meta;

        if (value?.isStore) {
            value = me.currentValueOf(value);
        }

        // A `lazy` field only gets a store when there is real data to apply: on load if `createStoreOnLoad`, later
        // only if this field owns its accessor. Otherwise the value is parked in `meta.initableValues` until then
        if (
            !store && me.lazy && value != null && (!Array.isArray(value) || value.length) &&
            (record.isConstructing ? me.createStoreOnLoad : me.$createsStoreOnAccess)
        ) {
            store = me.getOrCreateStore(record);
        }

        // Lazy store might not be created yet, gets created on first access. Returning false keeps the value for later
        // if called during init
        if (!store) {
            // Missing store suggests value was not yet initialized and future value resides
            // in a special meta property. In which case we need to update it there
            record.meta.initableValues.set(me, value);

            return false;
        }

        // In granular mode meta.modified holds a marker instead of the original value. Setting it
        // back (the revertChanges() flow) means "restore the store to its original state"
        if (value === granularModifiedMarker) {
            store.revertChanges();

            return;
        }

        // Prevent changes from leading to recursive calls
        if (store.$isSettingStoreFieldData) {
            return;
        }

        // While this field is propagating a change from its own store to the record, the incoming value
        // originates from that store - there is nothing to apply back, skip the costly data sync
        if (me.$isUpdatingRecord) {
            store.usesId = me.usesId || !store.count || !store.every(record => record.hasGeneratedId);

            return;
        }

        store.$isSettingStoreFieldData = true;

        // Call optional processing fn (processSubTasksStoreData for subTasks field) on the record, letting it
        // manipulate the data before creating records
        value = record[`process${StringHelper.capitalize(storeName)}Data`]?.(value, record) ?? value;

        // Apply incoming array to store
        if (!store.$preserveCurrentDataset) {
            store.data = value;
        }

        store.$isSettingStoreFieldData = false;

        // Keep track of if id should be included when serializing or not
        store.usesId = me.usesId || !store.count || !store.every(record => record.hasGeneratedId);
    }

    serialize(value, record) {
        const me = this;

        let store = record.meta[`${me.name}Store`];

        // No store yet for a `lazy` field. Serializing the raw value would skip the store's own persistable
        // representation (`processXxxStoreData`, date conversion), so create the store unless there is nothing to build
        if (!store) {
            if (value == null || (Array.isArray(value) && !value.length)) {
                return [];
            }

            store = me.getOrCreateStore(record);
        }

        return me.$isUpdatingRecord ? me.getValue(store, record) : me.currentValueOf(store);
    }

    // Extract persistable values, optionally including id depending on if ids are used
    getValue(store, record) {
        const getValueFnName = `get${StringHelper.capitalize(this.name)}StoreValue`;

        // delegate value getting to the record if it's able to handle that
        if (record[getValueFnName]) {
            return record[getValueFnName](store);
        }

        return store.allRecords.map(r => {
            const data = r.persistableData;

            if (!store.usesId) {
                delete data.id;
            }

            return data;
        });
    }

    isEqual(a, b) {
        // Reflexive - also avoids serializing a store field's records to compare the result with itself
        // (the engine commonly writes the field's own current value back)
        if (a === b) {
            return true;
        }

        if (this.$isUpdatingRecord && (a?.isStore || b?.isStore)) {
            const store = a?.isStore ? a : b;

            // While this field is propagating a change from its own store (granularly tracked mode), the
            // value is known to have changed - skip the expensive comparison of store content vs serialized
            // array. May report a persistable-wise identical value as changed, acceptable for the opt-in mode
            if (store.stm?.trackStoreDataFields) {
                return false;
            }

            // No cached pre-change value to compare against (first change after a dataset load) - and this
            // comparison only happens because the field's own store changed, so report it as changed
            if (store.$currentValue == null) {
                return false;
            }
        }

        if (a == null && b == null) {
            return true;
        }
        else if (a == null && b != null || a != null && b == null) {
            return false;
        }
        // here both `a` and `b` are not empty
        else {
            if (a.isStore && b.isStore) {
                return ObjectHelper.isDeeplyEqual(this.currentValueOf(a), this.currentValueOf(b));
            }
            else if (a.isStore && b.isStore || !a.isStore && !b.isStore) {
                return ObjectHelper.isEqual(a, b, true);
            }
            else {
                // here either `a` or `b` is a store, but not both
                const
                    store = a.isStore ? a : b,
                    modelClass = store.modelClass,
                    fields = modelClass.$meta.fields.defs,
                    storeEntries = this.currentValueOf(store),
                    arrayEntries = a.isStore ? b : a;

                if (storeEntries.length !== arrayEntries.length) {
                    return false;
                }
                else {
                    for (let i = 0; i < fields.length; i++) {
                        const field = fields[i];

                        if (!field.persist) {
                            continue;
                        }

                        for (let k = 0; k < storeEntries.length; k++) {
                            const storeValue = storeEntries[k][field.dataSource];
                            const arrayValue = arrayEntries[k][field.dataSource];

                            // few special cases for a value present in store, but missing in the array
                            if (storeValue !== undefined && arrayValue === undefined) {
                                // if id is missing in the array and is auto-generated in store - that is considered as equality
                                if (field.dataSource === modelClass.idField && isIdAutoGenerated(storeValue)) {
                                    continue;
                                }
                                // if there's no value in the array, but it presents in the store
                                // that still might be an equality case - if the store value is
                                // equal to the default field value
                                if (field.defaultValue !== undefined && ObjectHelper.isEqual(field.defaultValue, storeValue, true)) {
                                    continue;
                                }
                            }

                            if (!ObjectHelper.isEqual(storeValue, arrayValue, true)) {
                                return false;
                            }
                        }
                    }

                    return true;
                }
            }
        }
    }

    // Cloned value to be able to restore it later using STM
    getOldValue(record) {
        const store = record.meta[`${this.name}Store`];

        if (!store) {
            return null;
        }

        // With a granularly tracked store the STM records row actions instead of consuming this value,
        // it only ends up as the field's original value and in the update event payload. Safe to share
        // uncloned - the cached array is replaced on change, never mutated in place
        if (store.stm?.trackStoreDataFields) {
            return this.currentValueOf(store);
        }

        return ObjectHelper.clone(this.currentValueOf(store));
    }

    getAt(record, index) {
        const store = record.meta[`${this.name}Store`];
        return store?.getAt(index);
    }
}

